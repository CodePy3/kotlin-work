fun main() {
    val myAge = 29u // dataType: unsigned int
    val universeAge = 13_800_000_000L // dataType: Long
    val status = 'M' // dataType: Char 
    val name = "Sarah" // dataType: String
    val height = 1.78f // dataType: float 
    val root2 = Math.sqrt(2.0) // dataType: double
    val pi: Double = 3.14159

    println(myAge::class)
    println(universeAge::class)
    println(status::class)
    println(name::class)
    println(height::class)
    println(root2::class)
    println(pi::class)
}
